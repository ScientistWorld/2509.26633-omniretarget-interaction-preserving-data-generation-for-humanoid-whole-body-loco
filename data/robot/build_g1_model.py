"""Build the gym's robot model: Unitree G1 (29 DoF, sphere hands) as released
with the paper's code (holosoma_retargeting/models/g1/g1_29dof_spherehand.xml).

The output ``g1_29dof_spherehand_hull.xml`` is self-contained: visual-only
geoms, actuators, sensors and the ground plane are removed, and every
collision mesh is replaced by its convex hull written inline (MuJoCo collides
meshes through convex hulls; this gym additionally caps each hull at 128
vertices by deterministic farthest-point sampling, a documented geometry reduction).  Joint
position and velocity limits (velocity from the released URDF) are written to
``g1_limits.json``.

Usage: python data/robot/build_g1_model.py [--src data/downloads/holosoma/models/g1]
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

HERE = Path(__file__).resolve().parent


def read_mesh_vertices(path: Path) -> np.ndarray:
    data = path.read_bytes()
    if path.suffix.lower() == ".obj":
        verts = [line.split()[1:4] for line in data.decode(errors="ignore").splitlines() if line.startswith("v ")]
        return np.asarray(verts, dtype=float)
    # binary or ascii STL
    if data[:5] == b"solid" and b"facet" in data[:400]:
        verts = re.findall(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)", data)
        return np.asarray(verts, dtype=float)
    n = struct.unpack("<I", data[80:84])[0]
    rec = np.frombuffer(data[84:84 + 50 * n], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
    return rec["v"].reshape(-1, 3).astype(float)


def hull_vertices(v: np.ndarray, max_vertices: int = 128) -> np.ndarray:
    """Convex-hull vertices, thinned by farthest-point sampling to at most ``max_vertices``."""
    v = np.unique(np.round(v, 6), axis=0)
    hv = v[np.unique(ConvexHull(v).vertices)]
    if len(hv) <= max_vertices:
        return hv
    keep = [int(np.argmax(np.linalg.norm(hv - hv.mean(0), axis=1)))]
    d = np.linalg.norm(hv - hv[keep[0]], axis=1)
    while len(keep) < max_vertices:
        k = int(np.argmax(d))
        keep.append(k)
        d = np.minimum(d, np.linalg.norm(hv - hv[k], axis=1))
    sub = hv[keep]
    return sub[np.unique(ConvexHull(sub).vertices)]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=HERE.parents[1] / "data/downloads/holosoma/models/g1")
    ap.add_argument("--out", type=Path, default=HERE / "g1_29dof_spherehand_hull.xml")
    args = ap.parse_args()
    src_xml = args.src / "g1_29dof_spherehand.xml"
    tree = ET.parse(src_xml)
    root = tree.getroot()
    meshdir = args.src / "meshes"

    # Drop everything except compiler/asset/worldbody.
    for child in list(root):
        if child.tag not in ("compiler", "asset", "worldbody"):
            root.remove(child)
    root.find("compiler").attrib.pop("meshdir", None)
    worldbody = root.find("worldbody")
    used = set()

    def strip(parent):
        for el in list(parent):
            if el.tag == "geom":
                visual = el.get("contype") == "0" and el.get("conaffinity") == "0"
                if visual or el.get("type") == "plane" or el.get("name") == "ground":
                    parent.remove(el)
                    continue
                for k in ("rgba", "material", "density", "group"):
                    el.attrib.pop(k, None)
                if el.get("type") == "mesh":
                    used.add(el.get("mesh"))
            elif el.tag in ("site", "light", "camera"):
                parent.remove(el)
            else:
                strip(el)

    strip(worldbody)
    asset = root.find("asset")
    for el in list(asset):
        if el.tag != "mesh" or el.get("name") not in used:
            asset.remove(el)
            continue
        f = el.get("file")
        path = (meshdir / f) if not f.startswith("../") else (args.src / Path(f).name)
        if not path.exists():
            path = args.src / Path(f).name
        hv = hull_vertices(read_mesh_vertices(path))
        el.attrib.pop("file")
        el.set("vertex", " ".join(f"{x:.5f}" for x in hv.reshape(-1)))
    ET.indent(tree, space="  ")
    args.out.write_text("<!-- Generated by data/robot/build_g1_model.py from the released "
                        "g1_29dof_spherehand.xml (holosoma_retargeting, Apache-2.0). -->\n"
                        + ET.tostring(root, encoding="unicode") + "\n")

    # Limits: position from the MJCF, velocity from the released URDF.
    urdf = ET.parse(args.src / "g1_29dof_spherehand.urdf").getroot()
    vel = {j.get("name"): float(j.find("limit").get("velocity"))
           for j in urdf.iter("joint") if j.find("limit") is not None and j.get("type") in ("revolute", "continuous")}
    joints = []
    for j in worldbody.iter("joint"):
        lo, hi = (float(x) for x in j.get("range").split())
        joints.append({"name": j.get("name"), "range": [lo, hi], "velocity": vel[j.get("name")]})
    (HERE / "g1_limits.json").write_text(json.dumps({"robot_height": 1.32, "joints": joints}, indent=1) + "\n")
    print(f"wrote {args.out} ({args.out.stat().st_size / 1e3:.0f} kB), {len(used)} hull meshes, {len(joints)} joints")


if __name__ == "__main__":
    main()
